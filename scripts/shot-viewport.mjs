import { chromium } from "playwright";
const out = process.env.SHOTS_DIR ?? "/tmp/claude-0/-home-user-a-deti/42dfaa29-2a70-5db8-8c2b-99626f0d0113/scratchpad/shots";
const [url, name, w = "1440", h = "900", scrollY = "0"] = process.argv.slice(2);
const browser = await chromium.launch({ executablePath: "/opt/pw-browsers/chromium" }).catch(() => chromium.launch());
const page = await browser.newPage({ viewport: { width: Number(w), height: Number(h) } });
await page.goto(`http://localhost:3000${url}`, { waitUntil: "networkidle", timeout: 60000 });
await page.evaluate((y) => window.scrollTo(0, y), Number(scrollY));
await page.waitForTimeout(400);
await page.screenshot({ path: `${out}/${name}.png` });
await browser.close();
console.log("ok", name);
