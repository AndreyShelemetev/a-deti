import { chromium } from "playwright";
const out = process.env.SHOTS_DIR ?? "/tmp/claude-0/-home-user-a-deti/42dfaa29-2a70-5db8-8c2b-99626f0d0113/scratchpad/shots";
const base = process.env.BASE_URL ?? "http://localhost:3000";
const browser = await chromium.launch({ executablePath: "/opt/pw-browsers/chromium" }).catch(() => chromium.launch());
const page = await browser.newPage({ viewport: { width: 1440, height: 900 } });
page.on("dialog", (d) => d.accept());
await page.goto(`${base}/admin/login/`, { waitUntil: "networkidle" });
await page.fill('input[name="email"]', process.env.ADMIN_EMAIL ?? "admin@a-deti.ru");
await page.fill('input[name="password"]', process.env.ADMIN_PASSWORD ?? "admin12345");
await page.click('button[type="submit"]');
await page.waitForURL((u) => u.pathname.startsWith("/admin") && !u.pathname.includes("login"), { timeout: 30000 });
await page.goto(`${base}/admin/update/`, { waitUntil: "networkidle" });
console.log("current version shown:", (await page.locator("dl").first().innerText()).replace(/\s+/g, " ").slice(0, 120));
await page.click('button:has-text("Проверить")');
await page.waitForSelector("text=/Установлена последняя версия|Доступно обновлений/", { timeout: 60000 });
console.log("check:", await page.locator("text=/Установлена последняя версия|Доступно обновлений/").innerText());
await page.click('button:has-text("Обновить до")');
await page.waitForSelector("text=Обновление выполняется", { timeout: 30000 });
console.log("deploy started");
await page.waitForSelector("text=/dry run: done|Deploy finished/", { timeout: 120000 });
await page.waitForSelector("text=Установлена", { timeout: 1 }).catch(() => {});
await page.waitForTimeout(4000);
await page.screenshot({ path: `${out}/admin_update.png` });
const log = await page.locator("pre").innerText();
console.log("log tail:", log.split("\n").slice(-3).join(" | "));
await page.goto(`${base}/admin/update/`, { waitUntil: "networkidle" });
const history = await page.locator("table tbody tr").first().innerText();
console.log("history row:", history.replace(/\s+/g, " "));
await browser.close();
